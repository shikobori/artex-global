// Regression coverage for upstream a951e4a: fail-closed auth reads, atomic initial
// setup, and the password size limit. GetSetting distinguishes a missing key from
// a read failure only through its error (both return value=""). Treating an error
// as uninitialized would expose setup during a database outage. Closing the pool
// below forces read errors and verifies fail-closed HTTP 503 responses.
func TestAuthStatusFailsClosedWhenDataSourceUnavailable(t *testing.T) {
	m, err := NewManager(t.TempDir(), "")
	if err != nil {
		t.Skipf("postgres unavailable (%v) — skipping", err)
	}
	defer m.Close()
	if err := m.pg.Close(); err != nil {
		t.Fatal(err)
	}

	s := &Server{m: m}
	w := httptest.NewRecorder()
	s.authStatus(w, httptest.NewRequest("GET", "/api/auth/status", nil))

	if w.Code != 503 {
		t.Fatalf("status=%d, want 503 (treating read failures as uninitialized lets users overwrite the password through /setup); body=%s", w.Code, w.Body.String())
	}
	var payload struct {
		Initialized *bool `json:"initialized"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &payload); err == nil && payload.Initialized != nil {
		t.Fatalf("must not return initialized after a read failure: %v", *payload.Initialized)
	}
}

